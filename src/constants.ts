import { LagoonProject, LagoonEnvironment, ServiceType } from './types';

export interface ServiceTypeInfo {
  image: string;          // default base image
  build: boolean;         // generate a Dockerfile instead of pulling the image directly
  cliBuildArg: boolean;   // multi-stage build copying /app from the cli image
  persistent?: string;    // default lagoon.persistent path
  persistentName?: string;
  routes: boolean;        // gets autogenerated routes → joins amazeeio-network locally
  appVolume: boolean;     // mount .:/app:delegated for local dev
  buildSteps: string;     // default Dockerfile RUN steps, one per line
  env?: Record<string, string>; // extra local environment (Lagoon injects these itself on deploy)
  deprecated?: string;    // shown next to the type picker
}

