const service = (name: string, type: ServiceType, overrides: Partial<LagoonProject['services'][number]> = {}) => {
  const d = SERVICE_DEFAULTS[type];
  return {
    name,
    type,
    image: d.image,
    persistent: d.persistent ?? '',
    persistentName: d.persistentName ?? '',
    persistentSize: '',
    lagoonName: '',
    autogeneratedRoute: '' as const,
    port: '',
    buildSteps: d.buildSteps,
    volumes: '',
    ...overrides,
  };
};

